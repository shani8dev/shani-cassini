# The shipped file's shape, trimmed: the policy directives NUT's own template
# documents, one left commented, and the MONITOR line generated per-install by
# shani-settings' hook (so it is NOT here - see the credential test below).
SHIPPED = """## upsmon.conf - NUT's shutdown policy
# BEGIN shani-settings MONITOR (generated by the install hook; do not edit by hand)
# END shani-settings MONITOR
#MINSUPPLIES 1
MINSUPPLIES 1
SHUTDOWNCMD "/sbin/shutdown -h +0"
POWERDOWNFLAG /etc/killpower
DEADTIME 15
FINALDELAY 0
POLLFREQ 5
POLLFREQALERT 5
"""

# The deploy helper's validator is the other half of every bound asserted here,
# so the test reaches for it when it is in this checkout. Resolved relative to
# this file rather than typed as a literal path: a hardcoded home directory made
# this resolve to nothing on any machine but one, and the test then skipped
# itself without saying why.
_HELPER_CANDIDATES = [
    pathlib.Path(__file__).resolve().parent.parent.parent
    / "shani-deploy" / "scripts" / "shani-cassini-save.sh",
    pathlib.Path("/home/*/Documents/shani/shani-deploy/scripts/"
                 "shani-cassini-save.sh"),
]
HELPER = next((c for c in _HELPER_CANDIDATES if c.exists()), _HELPER_CANDIDATES[0])


def _walk(widget):
    out, stack = [], [widget]
    while stack:
        node = stack.pop()
        out.append(node)
        child = node.get_first_child()
        while child is not None:
            stack.append(child)
            child = child.get_next_sibling()
    return out


def _settle(tab):
    """Let the writer thread hand its answer back to the main loop."""
    from gi.repository import GLib
    ctx = GLib.MainContext.default()
    for _ in range(200):
        if not ctx.iteration(False):
            time.sleep(0.01)


@pytest.fixture
def page(tmp_path, monkeypatch):
    """The real page against a real file, with pkexec replaced by a write.

    The fake save **writes the file**, because the helper does. A fixture that
    only captured made the page look broken: a second Save re-read the ORIGINAL
    file, found the key still commented, correctly did nothing, and the test
    read that as a failure.
    """
    conf = tmp_path / "upsmon.conf"
    conf.write_text(SHIPPED)
    captured: dict = {}

    def fake_save(path, text, done):
        captured.clear()
        captured.update(text=text)
        pathlib.Path(path).write_text(text)
        done("", "")

    monkeypatch.setattr(up.ce, "save", fake_save)
    monkeypatch.setattr(up, "LOCAL_UPSMON_CONF", str(conf))
    tab = up.UpsTab()
    tab._render_policy()
    tab._captured = captured
    return tab


# --- the boundary ----------------------------------------------------------


def test_the_conf_path_is_a_real_nut_file_and_the_helper_validates_it():
    assert up.LOCAL_UPSMON_CONF == "/etc/nut/upsmon.conf", (
        "the page must edit NUT's shutdown policy, not a path it invented")
    assert config_io.helper_target_for(up.LOCAL_UPSMON_CONF) == "nut_upsmon_conf"
    argv = config_io.save_argv("nut_upsmon_conf", "0" * 64)
    assert argv[:2] == ["pkexec", config_io.SAVE_HELPER]
    assert "--expect-sha256" in argv


def test_upsd_users_is_NOT_editable_from_this_page():
    """The credential that can force a UPS power-down is not a settings field.

    shani-settings generates it once per install precisely so it is not a
    fleet-wide value; a page that could rewrite it would undo that.
    """
    keys = [k for k, *_ in up.POLICY]
    assert "upsmon" not in " ".join(keys)
    src = textwrap.dedent(inspect.getsource(up))
    assert "/etc/nut/upsd.users" not in src


def test_the_page_does_not_offer_a_battery_percentage():
    """NUT has no such knob, so a page offering one would be lying.

    apcupsd's BATTERYLEVEL/MINUTES have no upsmon equivalent; upsmon acts on the
    UPS hardware's own low-battery signal. The page says so instead of building
    a row that cannot work.
    """
    keys = [k for k, *_ in up.POLICY]
    for absent in ("BATTERYLEVEL", "MINUTES", "BATT", "LOWBATT"):
        assert absent not in keys, absent


def test_the_page_tells_the_user_there_is_no_percentage_threshold():
    """A page that is silent about a missing knob reads as broken.

    apcupsd's page had BATTERYLEVEL; upsmon has no equivalent. Saying so on the
    page is the difference between "this daemon does not work that way" and
    "this page is broken".
    """
    note = textwrap.dedent(inspect.getsource(up))
    assert "battery-percentage" in note or "low-battery signal" in note


def test_the_device_file_is_not_offered_as_a_field():
    """Which driver and which port are facts about the hardware.

    `nut-scanner -U` writes the right section, so a page offering UPSTYPE-style
    fields would let someone point the daemon at a protocol it does not speak -
    and that fails as a driver that exits silently rather than as an error.
    """
    keys = [k for k, *_ in up.POLICY]
    for absent in ("DRIVER", "PORT", "UPSTYPE", "UPSCABLE", "DEVICE"):
        assert absent not in keys, absent


# --- the separator, which is the silent one -------------------------------


def test_upsmon_conf_is_a_directive_file_with_no_equals_sign():
    """The premise of the writer, asserted directly: `KEY value`, no `=`."""
    assert "=" not in "".join(ln for ln in SHIPPED.splitlines()
                              if ln and not ln.startswith("#"))


def test_a_saved_line_names_the_key_upsmon_looks_up(page):
    """The written line, read back the way upsmon reads it."""
    page._entries["DEADTIME"].set_text("30")
    page._on_save_clicked(None, "DEADTIME")
    _settle(page)
    line = [ln for ln in page._captured["text"].splitlines()
            if ln.startswith("DEADTIME")][0]
    # A directive file: the key is the first token, and there is no '=' to get
    # wrong. Writing "DEADTIME=30" would still parse for a human but is not the
    # shape upsmon reads.
    assert line.split()[0] == "DEADTIME"
    assert "=" not in line.split(None, 1)[0]
    assert ce.current_value(page._captured["text"], "DEADTIME") == "30"


# --- values that change what the machine does ------------------------------


@pytest.mark.parametrize("key,bad", [
    ("DEADTIME", "0"),          # 0 means the UPS can never be declared gone
    ("DEADTIME", "soon"),
    ("POLLFREQ", "-1"),
    ("MINSUPPLIES", "0"),       # no supply can ever trigger shutdown
    ("MINSUPPLIES", "many"),
    ("FINALDELAY", "later"),
])
def test_a_value_outside_the_bounds_never_reaches_the_writer(page, key, bad):
    page._entries[key].set_text(bad)
    page._on_save_clicked(None, key)
    _settle(page)
    assert not page._captured, f"{key}={bad!r} was written anyway"
    assert "error" in page._entries[key].get_css_classes()


def test_an_unquoted_shutdown_command_is_refused(page):
    """Unquoted, only the first word is a command and the rest become arguments
    nothing reads - a shutdown that silently never happens."""
    page._entries["SHUTDOWNCMD"].set_text("/sbin/shutdown -h +0")
    page._on_save_clicked(None, "SHUTDOWNCMD")
    _settle(page)
    assert not page._captured
    assert "error" in page._entries["SHUTDOWNCMD"].get_css_classes()


def test_a_quoted_shutdown_command_is_accepted(page):
    page._entries["SHUTDOWNCMD"].set_text('"/sbin/shutdown -h +0"')
    page._on_save_clicked(None, "SHUTDOWNCMD")
    _settle(page)
    assert 'SHUTDOWNCMD "/sbin/shutdown -h +0"' in page._captured["text"]


def test_a_relative_powerdown_flag_is_refused(page):
    page._entries["POWERDOWNFLAG"].set_text("killpower")
    page._on_save_clicked(None, "POWERDOWNFLAG")
    _settle(page)
    assert not page._captured


def test_the_page_writes_what_the_helper_accepts(page):
    """Two independent implementations of one rule; drift between them is a
    save the page offers and the helper rejects."""
    if not HELPER.exists():
        pytest.skip("the helper is not in this checkout")
    page._entries["MINSUPPLIES"].set_text("2")
    page._on_save_clicked(None, "MINSUPPLIES")
    _settle(page)
    out = pathlib.Path("/tmp/ups-page-output.conf")
    out.write_text(page._captured["text"])
    proc = subprocess.run(["bash", str(HELPER), "--check-nut-upsmon-conf",
                           str(out)], capture_output=True, text=True)
    assert proc.returncode == 0, proc.stderr


