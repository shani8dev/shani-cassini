"""The UPS page's shutdown-policy controls, and the boundary around them.

This page was a reporter that told the user to go and edit a UPS daemon's config
in a terminal. It now edits that file. The point of this file is that "one file,
through one helper" is enforced rather than asserted in a comment.

**Why this file was rewritten.** apcupsd had had no upstream release since
3.14.14 (2016/2017); NUT is at 2.8.5 with its data model published as IETF RFC
9271. So the daemon, the file and the settings all changed, and the tests were
rewritten against the real NUT files rather than retargeted by find-and-replace.

**Two things this file is really about.**

1. **`upsmon.conf` is a DIRECTIVE file - `KEY value`, with no `=` and no
   sections.** That is a different shape from the INI-like `ups.conf` and
   `upsd.users` sitting beside it, and it matters: NUT's files use BOTH formats
   next to each other, so writing one parser for the other file is how the
   apcupsd validator came to refuse the distribution's own file - it inherited
   KEY=VALUE from a neighbouring systemd EnvironmentFile target and turned away
   a file that has no `=` in it at all. `config_edit.separator()` therefore reads
   the separator off the file instead of assuming one.

2. **These values decide whether the machine goes down when the power does.**
   A wrong one is not a failed form, it is a laptop that stays on until the UPS
   dies, or one that shuts down while the battery is nearly full. The bounds are
   checked before a password is asked for, and again by the helper.

**What NUT does NOT give us, and why no test asserts it.** apcupsd's page had a
BATTERYLEVEL percentage you could move; upsmon has no such knob - it responds to
the UPS hardware's own low-battery signal. A test asserting a percentage field
here would be testing a setting that does not exist, so the tests below assert
what the file really holds and the page states the difference to the user.
"""

