# --- the allowlist against the file shani-settings actually ships -------------
#
# `system_status._NUT_DIRECTIVES` is a hand-kept copy of what upsmon.conf can
# contain, and shani-settings ships the file. Two copies of one fact, in two
# repos, is the shape that produced every other drift this session found - the
# NUT driver list, the five sense-name tables, the package-hint table - so the
# one direction that matters is checked rather than asserted in a comment.
#
# The safe direction is a superset: a key the allowlist accepts but the shipped
# file does not yet set is forward compatibility, and `MONITOR` (generated by the
# install hook) and `HOSTSYNC` are exactly that. The harmful direction is the
# opposite - a key the file ships and the allowlist drops, which is a setting the
# page can never see.
def _shipped_upsmon_keys():
    """The live directives in shani-settings' upsmon.conf, or None if absent."""
    for candidate in (
        pathlib.Path(__file__).resolve().parents[2]
        / "shani-settings/etc/nut/upsmon.conf",
        pathlib.Path("/home/shrinivaskumbbar/Documents/shani/shani-settings/"
                     "etc/nut/upsmon.conf"),
    ):
        if candidate.is_file():
            keys = set()
            for line in candidate.read_text(encoding="utf-8").splitlines():
                stripped = line.strip()
                if not stripped or stripped.startswith("#"):
                    continue
                match = re.match(r"^([A-Z][A-Z0-9]+)\b", stripped)
                if match:
                    keys.add(match.group(1))
            return keys
    return None


def test_every_directive_the_shipped_file_sets_is_readable():
    """A key the collector's allowlist drops is a setting the UPS page can never
    show, which is the silent half of a hand-kept list drifting."""
    from shani_cassini import system_status as ss_mod
    shipped = _shipped_upsmon_keys()
    if shipped is None:
        pytest.skip("shani-settings is not beside this checkout")
    dropped = shipped - set(ss_mod._NUT_DIRECTIVES)
    assert not dropped, (
        "shani-settings' upsmon.conf sets directives the UPS page cannot read, "
        f"so those settings will never appear: {sorted(dropped)}")


def test_the_allowlist_is_not_merely_the_shipped_keys():
    """The guard for the check above: if the two lists ever became identical this
    test would pass because the comparison had nothing left to fail on. `MONITOR`
    and `HOSTSYNC` are the documented extras, and this asserts they are still
    there rather than assuming the superset."""
    from shani_cassini import system_status as ss_mod
    shipped = _shipped_upsmon_keys()
    if shipped is None:
        pytest.skip("shani-settings is not beside this checkout")
    assert set(ss_mod._NUT_DIRECTIVES) - shipped, (
        "the allowlist no longer accepts anything the shipped file does not set, "
        "so a key added to upsmon.conf would silently vanish from the page")
